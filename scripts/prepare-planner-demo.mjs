#!/usr/bin/env node
/**
 * prepare-planner-demo.mjs
 * ─────────────────────────────────────────────────────────────
 * Trims the Claude Design HTML export of the Nuki Planner into a demo suitable
 * for embedding as iframe inside /comercial. Patches applied to the source
 * (gzip+base64 modules inside the __bundler manifest):
 *
 *   1. useState('dashboard') → useState('typologies')
 *      Skips the empreendimento selector, opens directly in the first workflow step.
 *
 *   2. useState(null) for project state → lazy init from window.PlannerData.THE_PROJECT
 *      Ensures the demo is always inside "Parque Ibirapuera" (first project in the array).
 *
 *   3. navigate(dest) intercepts 'dashboard' → redirects to 'typologies'
 *      Prevents the sidebar "Empreendimentos" item (or any other jump) from landing
 *      the user back on the selector.
 *
 * Reads:  src/HTML/Nuki Planner.html
 * Writes: public/demos/planner/index.html
 *
 * Usage:
 *   cd nk-lp && node scripts/prepare-planner-demo.mjs
 *
 * Re-run this whenever the source HTML in src/HTML/ is regenerated by Claude Design.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import zlib from "node:zlib";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const SRC = join(ROOT, "src", "HTML", "Nuki Planner.html");
const OUT_DIR = join(ROOT, "public", "demos", "planner");
const OUT = join(OUT_DIR, "index.html");

console.log("[planner-demo] reading", SRC);
const html = readFileSync(SRC, "utf8");

// Extract the bundler manifest — one big JSON blob inside a script tag.
const MANIFEST_RE = /<script type="__bundler\/manifest">([\s\S]*?)<\/script>/;
const match = html.match(MANIFEST_RE);
if (!match) throw new Error("Manifest script tag not found in HTML");
const manifest = JSON.parse(match[1].trim());
const uuids = Object.keys(manifest);
console.log(`[planner-demo] manifest has ${uuids.length} entries`);

const b64ToBytes = (b64) => Buffer.from(b64, "base64");
const bytesToB64 = (bytes) => Buffer.from(bytes).toString("base64");

/** Get plain (utf8 or binary) bytes for an entry, decompressing if needed. */
const decodeEntry = (entry) => {
  const raw = b64ToBytes(entry.data);
  if (entry.compressed) return zlib.gunzipSync(raw);
  return raw;
};

const patches = { screen: 0, project: 0, navigate: 0 };
const patched = {};

for (const [uuid, entry] of Object.entries(manifest)) {
  const bytes = decodeEntry(entry);
  const text = bytes.toString("utf8");

  // Skip anything that doesn't look like source code — pass through unchanged.
  // Content sniff avoids needing to inspect entry.type per manifest format.
  const looksLikeSource =
    text.includes("React") || text.includes("useState") || text.includes("navigate");

  if (!looksLikeSource) {
    patched[uuid] = entry;
    continue;
  }

  let out = text;

  // Patch 1: initial screen dashboard → typologies (first workflow step inside project)
  if (out.includes("useState('dashboard')") || out.includes('useState("dashboard")')) {
    out = out
      .replace(/useState\('dashboard'\)/g, "useState('typologies')")
      .replace(/useState\("dashboard"\)/g, "useState('typologies')");
    patches.screen++;
  }

  // Patch 2: project state null → lazy init from PlannerData
  // Pattern: `const [project, setProject] = React.useState(null)` (whitespace-tolerant)
  const projectRE =
    /const\s*\[\s*project\s*,\s*setProject\s*\]\s*=\s*React\.useState\(\s*null\s*\)/;
  if (projectRE.test(out)) {
    out = out.replace(
      projectRE,
      "const [project, setProject] = React.useState(() => (window.PlannerData || {}).THE_PROJECT || null)",
    );
    patches.project++;
  }

  // Patch 3: navigate arrow function → intercept 'dashboard' target
  // Pattern: `const navigate = (dest, params = {}) => {` (whitespace-tolerant)
  const navigateRE =
    /const\s+navigate\s*=\s*\(\s*dest\s*,\s*params\s*=\s*\{\s*\}\s*\)\s*=>\s*\{/;
  if (navigateRE.test(out)) {
    out = out.replace(
      navigateRE,
      "const navigate = (dest, params = {}) => { if (dest === 'dashboard') dest = 'typologies';",
    );
    patches.navigate++;
  }

  if (out === text) {
    // No changes — keep original (compressed or not).
    patched[uuid] = entry;
  } else {
    // Re-encode as PLAIN base64 (no gzip) — simpler for debugging, marginal size hit.
    patched[uuid] = {
      ...entry,
      compressed: false,
      data: bytesToB64(Buffer.from(out, "utf8")),
    };
    console.log(
      `[planner-demo] patched ${uuid.slice(0, 8)}… (was ${entry.compressed ? "gzipped" : "plain"}, now plain)`,
    );
  }
}

console.log("[planner-demo] patches applied:", patches);

if (patches.screen === 0 || patches.project === 0) {
  console.warn(
    "[planner-demo] WARN: critical patches missed — verify regex vs source. Output may not skip dashboard.",
  );
}
if (patches.navigate === 0) {
  console.warn(
    "[planner-demo] WARN: navigate() intercept not applied — sidebar 'Empreendimentos' may still work.",
  );
}

// ESC bridge — injeta um listener global que roda com { capture: true }, então
// dispara ANTES de qualquer handler React interno. Quando o HTML é embutido
// como iframe em outra página (window.parent !== window), o parent recebe
// postMessage({ type: 'nuki-demo:esc' }) e responde saindo do modo demo.
// Persiste depois da troca de body feita pelo loader (listener no window).
const ESC_BRIDGE = `<script>
(function(){
  window.addEventListener('keydown', function(e){
    if (e.key === 'Escape' && window.parent !== window) {
      e.preventDefault();
      try { window.parent.postMessage({ type: 'nuki-demo:esc' }, '*'); } catch(_){}
    }
  }, { capture: true });
})();
</script>`;

// Reassemble manifest and inject back into the HTML.
const newManifestJson = JSON.stringify(patched);
let newHtml = html.replace(
  MANIFEST_RE,
  `<script type="__bundler/manifest">${newManifestJson}</script>`,
);

// Injetar a bridge no head — antes do </head>.
if (newHtml.includes("</head>")) {
  newHtml = newHtml.replace("</head>", `${ESC_BRIDGE}\n</head>`);
} else {
  console.warn("[planner-demo] WARN: </head> not found, ESC bridge not injected");
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, newHtml, "utf8");

const inputKB = (html.length / 1024).toFixed(0);
const outputKB = (newHtml.length / 1024).toFixed(0);
console.log(
  `[planner-demo] wrote ${OUT}\n              ${outputKB} KB output (input ${inputKB} KB source)`,
);
